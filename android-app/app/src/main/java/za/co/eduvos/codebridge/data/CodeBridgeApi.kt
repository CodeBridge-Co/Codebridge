package za.co.eduvos.codebridge.data

/**
 * Backend API Contract for CodeBridge (Java REST API & Python AI Evaluation Service).
 * Use this interface to connect your live Java/Python backend services.
 */
interface CodeBridgeApi {
    suspend fun getChallenges(category: String? = null): List<Challenge>
    suspend fun getCompanyChallenges(companyName: String? = null): List<CompanyChallenge>
    suspend fun submitCode(problemId: Int, code: String, language: String): CodeSubmissionResult
    suspend fun requestAiHint(problemId: Int, code: String): String
    suspend fun executeGitCommand(command: String): String
    suspend fun submitVerbalAnswer(questionId: Int, audioBytes: ByteArray): VerbalResult
    suspend fun getAiEvaluation(submissionId: String): AiEvaluationResponse
    suspend fun getUserProgress(): UserProgressData
}

data class CompanyChallenge(
    val id: Int,
    val companyName: String,
    val title: String,
    val description: String,
    val difficulty: String,
    val language: String,
    val tag: String
)

data class CodeSubmissionResult(
    val success: Boolean,
    val passedCases: Int,
    val totalCases: Int,
    val errorMessage: String? = null
)

data class VerbalResult(
    val questionId: Int,
    val score: Int,
    val feedback: String
)

/**
 * Python AI Synthesis Response Contract.
 * Generated by Python AI Service after analyzing code, git commits, and verbal recordings.
 */
data class AiEvaluationResponse(
    val submissionId: String,
    val overallScorePercent: Int,
    val strengths: String,
    val areasToImprove: String,
    val aiSummaryOverview: String
)

data class UserProgressData(
    val solvedCount: Int,
    val totalTimeMinutes: Int,
    val avgScorePercent: Int,
    val completedChallenges: List<Challenge>,
    val inProgressChallenges: List<Challenge>
)
